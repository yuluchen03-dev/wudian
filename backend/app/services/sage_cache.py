# 匹配逻辑
# ============================================================
def match_safe_qa(question: str) -> Optional[Dict[str, Any]]:
    """
    用关键词模糊匹配安全问答缓存。

    匹配规则：
    - 遍历 SAFE_QA_CACHE，若 question 命中任意 keyword，返回该缓存项
    - 命中多个时，返回命中关键词最多的那项（更精准）
    - 无命中返回 None

    返回的 dict 会附带一个 "cache_key" 字段，标识命中的缓存项。
    """
    if not question:
        return None

    q = question.strip().lower()
    best_match: Optional[Dict[str, Any]] = None
    best_hits = 0

    for cache_key, item in SAFE_QA_CACHE.items():
        keywords: List[str] = item.get("keywords", [])
        hits = sum(1 for kw in keywords if kw.lower() in q)
        if hits > best_hits:
            best_hits = hits
            # 返回副本，附上 cache_key，避免污染原数据
            best_match = {**item, "cache_key": cache_key}

    if best_match:
        logger.info(
            "sage_cache 命中: cache_key=%s, hits=%d, question=%s",
            best_match.get("cache_key"), best_hits, question[:50],
        )
    return best_match


def get_fallback_qa(question: str = "") -> Dict[str, Any]:
    """
    LLM 调用失败时的兜底：尝试匹配最相似的缓存项，
    匹配不到则返回第一个安全问答（保证总有回应）。
    """
    matched = match_safe_qa(question)
    if matched:
        return matched
    # 兜底的兜底：返回第一个安全问答
    first_key = next(iter(SAFE_QA_CACHE))
    logger.warning(
        "sage_cache 未命中任何安全问答，返回默认兜底: %s", first_key
    )
    return {**SAFE_QA_CACHE[first_key], "cache_key": first_key}


def has_safe_qa(question: str) -> bool:
    """快速判断是否有匹配的安全问答（不返回内容）"""
    return match_safe_qa(question) is not None
