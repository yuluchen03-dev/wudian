SAGES: Dict[str, SagePersona] = {
    "confucius": CONFUCIUS,
    "mencius": MENCIUS,
    "wang_yangming": WANG_YANGMING,
    "laozi": LAOZI,
    "mozi": MOZI,
    "hanfeizi": HANFEIZI,
    "li_bai": LI_BAI,
    "su_shi": SU_SHI,
    "fan_zhongyan": FAN_ZHONGYAN,
    "wang_anshi": WANG_ANSHI,
    "zhuge_liang": ZHUGE_LIANG,
}


def get_sage(sage_key: str) -> SagePersona:
    """根据 key 获取圣贤设定"""
    if sage_key not in SAGES:
        raise ValueError(
            f"未知圣贤: {sage_key}，可选: {list(SAGES.keys())}"
        )
    return SAGES[sage_key]


def build_sage_system_prompt(sage_key: str, rag_context: str) -> str:
    """构建圣贤对话的完整 system prompt（含免责声明 + RAG 上下文 + 角色设定）"""
    sage = get_sage(sage_key)
    persona_block = f"""【你扮演的角色】
姓名：{sage.name}（{sage.courtesy}）
年代：{sage.era}

【核心思想】
{sage.core_thought}

【典型观点】
{sage.typical_views}

【说话风格】
{sage.style}

【硬性要求】
1. 始终以 {sage.name} 的身份、语气、思想回答，不可出戏。
2. 回答要体现其核心思想，不可与其他先贤混淆。
3. 用其典型语言风格，但要让现代读者能理解。
4. 回答必须使用以下结构化格式输出，便于前端分区渲染：

<<<QUOTE>>>
（引用的经典原文，若无 RAG 原文则填"无"。注意：必须是真实存在的原文，不可杜撰）
<<<SOURCE>>>
（原文出处，如"《论语·学而》"；无原文则填"无"）
<<<CLASSICAL>>>
（用 {sage.name} 的口吻对用户问题的文言回应，3-6 句，体现其核心思想与说话风格）
<<<VERNACULAR>>>
（对上方文言的白话点睛，1-3 句，帮现代读者抓住重点）
<<<DISCLAIMER>>>
（免责声明：以上为基于该先贤思想体系的现代演绎，非历史人物原话）

5. 若 RAG 检索到了相关原文，QUOTE 必须引用检索结果中的原文，SOURCE 必须填写真实出处。
6. 若 RAG 无匹配原文，QUOTE 填"无"，SOURCE 填"无"，CLASSICAL 中需注明"此为思想演绎，非原话"。
7. 严禁在 QUOTE 中编造不存在的经典原文。宁可填"无"也不可杜撰。
"""
    prefix = SAGE_CHAT_SYSTEM_PREFIX.format(rag_context=rag_context or "（无参考原文）")
    return f"{prefix}\n{persona_block}"


def get_sage_name(sage_key: str) -> str:
    return get_sage(sage_key).name
